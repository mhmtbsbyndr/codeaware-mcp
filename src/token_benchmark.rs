//! Token benchmark.
//!
//! Two parts live here:
//! 1. Compression fixtures (`run_token_benchmarks`): raw vs compressed size per fixture.
//! 2. The task-suite benchmark (`run_suite`): for each git-derived task, what each
//!    retrieval variant returns and how much of the ground-truth file set it covers.
//!
//! ESTIMATOR CAVEAT: every number is produced by `token_stats::estimate_tokens`, a
//! chars/words heuristic (`max(ceil(chars/4), ceil(words*4/3))`). It is an ESTIMATE,
//! not a real tokenizer. Absolute counts will differ from model tokenizers (code is
//! often denser than prose). Use it for relative comparison between variants.
//! To use a real tokenizer, pass another `TokenCounter` to `SuiteConfig::counter`,
//! e.g. a wrapper around `tiktoken-rs` or the provider's count-tokens endpoint, and
//! keep the same counter for every variant so the comparison stays fair.

